
const GITHUB_API = 'https://api.github.com'
const OSV_API = 'https://api.osv.dev/v1/querybatch'

// Read JSON from an API or GitHub raw file
async function readJson(url, options = {}) {
  const response = await fetch(url, options)

  if (!response.ok) {
    const error = new Error(
      response.status === 404
        ? 'File or repository not found.'
        : response.status === 403
          ? 'GitHub API rate limit reached. Please try again later.'
          : `Request failed (${response.status}).`
    )

    error.status = response.status
    throw error
  }

  return response.json()
}

// Get the actual package name from its installed path
function getPackageName(packagePath, metadata) {
  if (metadata?.name) return metadata.name

  let packagePart = packagePath.split('/node_modules/').pop()
  packagePart = packagePart.replace(/^node_modules\//, '')

  const parts = packagePart.split('/')

  return parts[0].startsWith('@')
    ? `${parts[0]}/${parts[1]}`
    : parts[0]
}

// Find the installed location of a dependency
function resolveInstalledPath(parentPath, packageName, packageMap) {
  let current = parentPath

  while (true) {
    const candidate = current
      ? `${current}/node_modules/${packageName}`
      : `node_modules/${packageName}`

    if (packageMap[candidate]) return candidate

    if (!current) break

    const marker = current.lastIndexOf('/node_modules/')
    current = marker === -1 ? '' : current.slice(0, marker)
  }

  return null
}

// Build the dependency tree
function makeDependencyNode(
  packagePath,
  packageMap,
  vulnerabilityMap,
  ancestors = new Set()
) {
  const metadata = packageMap[packagePath]

  if (!metadata || ancestors.has(packagePath)) return null

  const nextAncestors = new Set(ancestors)
  nextAncestors.add(packagePath)

  const dependencies = {
    ...(metadata.dependencies || {}),
    ...(metadata.optionalDependencies || {}),
  }

  const children = Object.entries(dependencies).flatMap(([name]) => {
    const childPath = resolveInstalledPath(
      packagePath,
      name,
      packageMap
    )

    if (!childPath) return []

    const child = makeDependencyNode(
      childPath,
      packageMap,
      vulnerabilityMap,
      nextAncestors
    )

    return child ? [child] : []
  })

  const name = getPackageName(packagePath, metadata)
  const version = metadata.version || 'unknown'
  const key = `${name}@${version}`
  const vulnerabilities = vulnerabilityMap.get(key) || []

  return {
    id: packagePath,
    name,
    version,
    type: metadata.dev ? 'Development' : 'Production',
    status: vulnerabilities.length ? 'Vulnerable' : 'Safe',
    vulnerabilities,
    children,
  }
}

// Read dependencies from package-lock.json
function collectPackages(lockfile) {
  if (!lockfile.packages) {
    throw new Error(
      'Unsupported lock file format. Please use package-lock.json generated by npm v7 or later.'
    )
  }

  const packageMap = lockfile.packages
  const root = packageMap[''] || {}

  const rootDependencies = {
    ...(root.dependencies || {}),
    ...(root.devDependencies || {}),
    ...(root.optionalDependencies || {}),
  }

  const direct = Object.keys(rootDependencies).flatMap((name) => {
    const packagePath = resolveInstalledPath('', name, packageMap)

    return packagePath ? [{ name, packagePath }] : []
  })

  return { packageMap, direct }
}

// Determine vulnerability severity
function severityFor(vulnerability) {
  const databaseSeverity =
    vulnerability.database_specific?.severity?.toUpperCase()

  if (
    ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW'].includes(databaseSeverity)
  ) {
    return databaseSeverity
  }

  const scores = (vulnerability.severity || [])
    .map((item) => Number(item.score))
    .filter(Number.isFinite)

  const score = scores.length ? Math.max(...scores) : 0

  if (score >= 9) return 'CRITICAL'
  if (score >= 7) return 'HIGH'
  if (score >= 4) return 'MEDIUM'

  return 'LOW'
}

// Check packages using OSV.dev
async function checkOSV(packages) {
  const unique = [
    ...new Map(
      packages.map((item) => [
        `${item.name}@${item.version}`,
        item,
      ])
    ).values(),
  ]

  const results = []

  for (let index = 0; index < unique.length; index += 100) {
    const batch = unique.slice(index, index + 100)

    const response = await readJson(OSV_API, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        queries: batch.map(({ name, version }) => ({
          package: {
            name,
            ecosystem: 'npm',
          },
          version,
        })),
      }),
    })

    results.push(...(response.results || []))
  }

  const map = new Map()

  unique.forEach((item, index) => {
    const vulnerabilities = (results[index]?.vulns || []).map(
      (vulnerability) => ({
        id: vulnerability.id,
        summary:
          vulnerability.summary ||
          vulnerability.details?.split('\n')[0] ||
          'Known security vulnerability',
        severity: severityFor(vulnerability),
        modified: vulnerability.modified || null,
        url: `https://osv.dev/vulnerability/${vulnerability.id}`,
      })
    )

    map.set(
      `${item.name}@${item.version}`,
      vulnerabilities
    )
  })

  return map
}

// Flatten dependency tree
function flattenTree(nodes, output = []) {
  nodes.forEach((node) => {
    output.push({
      name: node.name,
      version: node.version,
    })

    flattenTree(node.children || [], output)
  })

  return output
}

// Count all dependencies in the tree
function countTree(nodes) {
  return nodes.reduce(
    (total, node) =>
      total + 1 + countTree(node.children || []),
    0
  )
}

// Count vulnerability severities
function countSeverities(
  nodes,
  counts = {
    critical: 0,
    high: 0,
    medium: 0,
    low: 0,
  }
) {
  nodes.forEach((node) => {
    node.vulnerabilities.forEach((vulnerability) => {
      const key = vulnerability.severity.toLowerCase()

      if (key in counts) {
        counts[key] += 1
      }
    })

    countSeverities(node.children || [], counts)
  })

  return counts
}

// Collect vulnerabilities from dependency tree
function collectTreeVulnerabilities(nodes, output = []) {
  nodes.forEach((node) => {
    node.vulnerabilities.forEach((vulnerability) => {
      output.push({
        ...vulnerability,
        package: node.name,
        version: node.version,
      })
    })

    collectTreeVulnerabilities(
      node.children || [],
      output
    )
  })

  return output
}

// Shared scanning logic for GitHub and local projects
async function analyzeLockfile(lockfile, projectInfo) {
  const startedAt = performance.now()

  const { packageMap, direct } = collectPackages(lockfile)

  if (!direct.length) {
    throw new Error(
      'No npm dependencies were found in this project lock file.'
    )
  }

  const installedPackages = Object.entries(packageMap)
    .filter(
      ([path, metadata]) =>
        path &&
        path.includes('node_modules/') &&
        metadata.version
    )
    .map(([path, metadata]) => ({
      name: getPackageName(path, metadata),
      version: metadata.version,
    }))

  if (!installedPackages.length) {
    throw new Error('No installed npm packages were found.')
  }

  const vulnerabilityMap = await checkOSV(installedPackages)

  const tree = direct
    .map(({ packagePath }) =>
      makeDependencyNode(
        packagePath,
        packageMap,
        vulnerabilityMap
      )
    )
    .filter(Boolean)

  const vulnerabilities = collectTreeVulnerabilities(tree)
  const severity = countSeverities(tree)
  const packages = countTree(tree)

  return {
    repository: projectInfo.repository,
    repositoryUrl: projectInfo.repositoryUrl || '',
    branch: projectInfo.branch,
    commit: projectInfo.commit,
    source: projectInfo.source,
    scanner: 'DepShield + OSV.dev',
    lockfile: projectInfo.lockfile,
    dependencies: tree,
    vulnerabilities,
    packages,
    directDependencies: direct.length,
    transitiveDependencies: Math.max(
      0,
      packages - direct.length
    ),
    vulnerabilityCount: vulnerabilities.length,
    critical: severity.critical,
    high: severity.high,
    medium: severity.medium,
    low: severity.low,
    duration: `${(
      (performance.now() - startedAt) /
      1000
    ).toFixed(1)} sec`,
    status: 'Completed',
  }
}

// Scan a public GitHub repository
export async function scanGithubRepository(repositoryUrl) {
  let parsed

  try {
    parsed = new URL(repositoryUrl)
  } catch {
    throw new Error('Enter a valid GitHub repository URL.')
  }

  if (
    parsed.protocol !== 'https:' ||
    parsed.hostname !== 'github.com'
  ) {
    throw new Error('Please enter a valid public GitHub URL.')
  }

  const parts = parsed.pathname.split('/').filter(Boolean)

  const owner = parts[0]
  const repository = parts[1]?.replace(/\.git$/i, '')

  if (!owner || !repository) {
    throw new Error('Enter a valid GitHub repository URL.')
  }

  const repoInfo = await readJson(
    `${GITHUB_API}/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}`
  )

  const branch = repoInfo.default_branch || 'main'

  const commitInfo = await readJson(
    `${GITHUB_API}/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/commits/${encodeURIComponent(branch)}`
  )

  const encodedBranch = encodeURIComponent(branch).replace(
    /%2F/g,
    '/'
  )

  const rawBase =
    `https://raw.githubusercontent.com/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/${encodedBranch}`

  let lockfile
  let lockfileName = 'package-lock.json'

  try {
    lockfile = await readJson(
      `${rawBase}/package-lock.json`
    )
  } catch (error) {
    if (error.status !== 404) throw error

    lockfileName = 'npm-shrinkwrap.json'

    lockfile = await readJson(
      `${rawBase}/npm-shrinkwrap.json`
    )
  }

  return analyzeLockfile(lockfile, {
    repository: repoInfo.name || repository,
    repositoryUrl: repoInfo.html_url || repositoryUrl,
    branch,
    commit: commitInfo.sha
      ? commitInfo.sha.slice(0, 7)
      : branch,
    source: 'Public GitHub repository',
    lockfile: lockfileName,
  })
}

// Scan a project selected from the user's computer
export async function scanLocalProject(
  lockfile,
  projectName,
  lockfileName = 'package-lock.json'
) {
  if (!lockfile || typeof lockfile !== 'object') {
    throw new Error('Could not read the selected project lock file.')
  }

  return analyzeLockfile(lockfile, {
    repository: projectName || 'Local Project',
    repositoryUrl: '',
    branch: 'Local project',
    commit: 'Local',
    source: 'Local computer folder',
    lockfile: lockfileName,
  })
}
